import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import os from "node:os";
import { spawnSync } from "node:child_process";
import {
  build,
  write,
  sha,
  extractFrames,
  stageManifest,
} from "../src/broll/curate.mjs";

test("mixed provider build keeps each actual source, license and display label; fixtures remain unstageable", async () => {
  const work = fs.mkdtempSync(path.join(os.tmpdir(), "dnt-mixed-broll-"));
  try {
    const fixture = path.join(work, "fixture.mp4");
    assert.equal(
      spawnSync(
        "ffmpeg",
        [
          "-hide_banner",
          "-loglevel",
          "error",
          "-y",
          "-f",
          "lavfi",
          "-i",
          "color=c=navy:s=640x360:r=30:d=2",
          "-c:v",
          "libx264",
          "-pix_fmt",
          "yuv420p",
          fixture,
        ],
        { windowsHide: true },
      ).status,
      0,
    );
    const stamp = new Date().toISOString(),
      candidates = [],
      reviews = [],
      scenes = [];
    for (const [i, provider] of ["pexels", "pixabay"].entries()) {
      const scene = {
        id: "scene-" + i,
        start: i,
        end: i + 1,
        duration: 1,
        claim_kind: "illustration",
        display_label: "Synthetic fixture only " + i,
        fallback: { kind: "test" },
      };
      scenes.push(scene);
      const id = provider + "-" + (10 + i),
        fileId = 100 + i,
        relative = `cache/${id}-${fileId}.mp4`,
        dest = path.join(work, relative);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      fs.copyFileSync(fixture, dest);
      write(dest + ".json", { sha256: sha(dest) });
      const source =
          provider === "pixabay"
            ? `https://pixabay.com/videos/id-${10 + i}/`
            : `https://www.pexels.com/video/${10 + i}/`,
        license =
          provider === "pixabay"
            ? "https://pixabay.com/service/license-summary/"
            : "https://www.pexels.com/license/",
        terms =
          provider === "pixabay"
            ? "https://pixabay.com/service/terms/"
            : "https://www.pexels.com/terms-of-service/";
      const c = {
        id,
        provider,
        scene_id: scene.id,
        source_url: source,
        author: {
          name: "Synthetic test fixture",
          url: "https://example.invalid/fixture",
        },
        preview: {
          path: relative,
          sha256: sha(dest),
          window: { in: 0, out: 1 },
        },
        frames: extractFrames(dest, work, scene.id, 0, 1),
        full_file: {
          id: fileId,
          link: "https://example.invalid/must-not-fetch.mp4",
          width: 640,
          height: 360,
        },
      };
      candidates.push(c);
      reviews.push({
        scene_id: scene.id,
        candidate_id: id,
        decision: "approve",
        reviewer: "synthetic-fixture-only",
        reviewed_at: stamp,
        preview_sha256: c.preview.sha256,
        frames_seen: c.frames.map((f) => f.sha256),
        observations:
          "Synthetic navy frames generated by FFmpeg, never actual footage approval.",
        segment: { in: 0, out: 1 },
        content_kind: "generic_illustration",
        layout: "contain",
        rights: {
          status: "verified",
          checked_at: stamp,
          checked_by: "synthetic-fixture-only",
          source_page: source,
          license_url: license,
          terms_url: terms,
          evidence:
            "Synthetic record used to test dispatch; not a real rights review.",
          third_party_clearance: "not_needed",
          third_party_notes:
            "Only generated solid color; no real copyrighted stock material.",
          attribution_required: false,
        },
      });
    }
    write(path.join(work, "plan.json"), {
      schema_version: 1,
      script_sha256: "fixture-only",
      duration: 2,
      fps: 30,
      scenes,
    });
    write(path.join(work, "candidates.json"), {
      provider: "pixabay",
      mode: "fixture",
      plan_sha256: sha(path.join(work, "plan.json")),
      api_requests: 0,
      searches: [],
      candidates,
    });
    write(path.join(work, "reviews.json"), { reviews });
    const m = await build(work, {
      testMode: true,
      fetcher: () => assert.fail("cached fixture must not access network"),
    });
    assert.deepEqual(
      m.entries.map((e) => e.status),
      ["selected", "selected"],
    );
    assert.deepEqual(
      m.entries.map((e) => e.source.provider),
      ["Pexels", "Pixabay"],
    );
    assert.deepEqual(m.providers, ["Pexels", "Pixabay"]);
    for (const [i, e] of m.entries.entries()) {
      assert.equal(e.display_label, scenes[i].display_label);
      assert.equal(m.credits[i].license_url, reviews[i].rights.license_url);
      assert.equal(e.processing.source_width, 640);
      assert.equal(e.processing.source_height, 360);
    }
    assert.throws(
      () =>
        stageManifest(
          path.join(work, "broll_manifest.json"),
          path.join(work, "public"),
        ),
      /Fixture/,
    );
  } finally {
    assert(path.resolve(work).startsWith(path.resolve(os.tmpdir()) + path.sep));
    fs.rmSync(work, { recursive: true, force: true });
  }
});
